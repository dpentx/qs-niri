#!/usr/bin/env python3
"""Regenerate modules/bar/components/emojiData.js.

Sources (npm): emojibase-data (emoji, groups, English tags) and
cldr-annotations-full (Turkish names and keywords).
  npm install emojibase-data cldr-annotations-full
  scripts/gen-emoji-data.py <dir containing node_modules> > modules/bar/components/emojiData.js
Skin-tone variants are left out on purpose; the base emoji is listed once.
"""
import json, sys

nm = sys.argv[1].rstrip("/") + "/node_modules"
emojis = json.load(open(f"{nm}/emojibase-data/en/compact.json"))
tr = json.load(open(f"{nm}/cldr-annotations-full/annotations/tr/annotations.json"))["annotations"]["annotations"]

# emojibase groups -> tab index: smileys+people, animals, food, places, activities, objects, symbols, flags
tab = {0: 0, 1: 0, 3: 1, 4: 2, 5: 3, 6: 4, 7: 5, 8: 6, 9: 7}
rows = []
for e in sorted((e for e in emojis if e.get("group") in tab), key=lambda e: e["order"]):
    ch = e["unicode"]
    words = [e["label"]] + e.get("tags", [])
    t = tr.get(ch) or tr.get(ch.replace("️", "")) or {}
    words += t.get("tts", []) + t.get("default", [])
    seen, kw = set(), []
    for w in " ".join(words).lower().split():
        if w not in seen:
            seen.add(w); kw.append(w)
    rows.append([ch, tab[e["group"]], " ".join(kw)])

print(".pragma library\n// Generated by scripts/gen-emoji-data.py, do not edit by hand.\n// [emoji, tab, search keywords (English + Turkish)]")
print("var all = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";")
